export type Locale = "pt" | "en";
const DICTS: Record<Locale, Dict> = { pt, en };
const STORAGE_KEY = "sentinel.locale";

interface I18nState {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: (key: MessageKey) => string;
  formatDate: (iso: string | null | undefined) => string;
  formatRelative: (iso: string | null | undefined) => string;
}

const I18nContext = createContext<I18nState | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("pt");

  useEffect(() => {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved === "pt" || saved === "en") setLocaleState(saved);
    } catch {
      /* armazenamento indisponível: fica em português */
    }
  }, []);

  useEffect(() => {
    document.documentElement.lang = locale === "pt" ? "pt-BR" : "en";
  }, [locale]);

  const setLocale = useCallback((l: Locale) => {
    setLocaleState(l);
    try {
      localStorage.setItem(STORAGE_KEY, l);
    } catch {
      /* ignora */
    }
  }, []);

  const value = useMemo<I18nState>(() => {
    const tag = locale === "pt" ? "pt-BR" : "en-US";
    const dtf = new Intl.DateTimeFormat(tag, { dateStyle: "short", timeStyle: "short" });
    const rtf = new Intl.RelativeTimeFormat(tag, { numeric: "auto" });
    return {
      locale,
      setLocale,
      t: (key) => DICTS[locale][key] ?? pt[key] ?? key,
      formatDate: (iso) => (iso ? dtf.format(new Date(iso)) : "—"),
      formatRelative: (iso) => {
        if (!iso) return "—";
        const s = Math.round((new Date(iso).getTime() - Date.now()) / 1000);
        const abs = Math.abs(s);
        if (abs < 60) return rtf.format(s, "second");
        if (abs < 3600) return rtf.format(Math.round(s / 60), "minute");
        if (abs < 86400) return rtf.format(Math.round(s / 3600), "hour");
        return rtf.format(Math.round(s / 86400), "day");
      },
    };
  }, [locale, setLocale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nState {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n precisa de <I18nProvider>");
  return ctx;
}
